# Вашему серверу на вход прилетает IP-адрес (v4) клиента. Нужно определить, что IP-адрес – правильный.
#
# IP-адрес (v4) считается правильным, когда его размер составляет 4 байта и состоит он из 4-х чисел.
# На каждое число приходится 1 байт, и следовательно максимальное число, которое там помещается – 255, а минимальное 0.
# Условия:
# Каждое число находится в интервале от 0 до 255 включительно.
# IP адрес не может быть 0.0.0.0 или 255.255.255.255, так как они зарезервированы для специального назначения.
# На вход вашей программе поступают 4 целых неотрицательных числа,
# разделенных точкой n1, n2, n3, n4 – они уже введены в программу, снова вводить их не нужно!
#
# В качестве ответа выведите True если IP-адрес правильный или False если неправильный.
n1, n2, n3, n4 = [int(i) for i in input().split('.')]
# ваш код ниже (используйте переменные n1-n4)
print(
    all(0 <= n <= 255 for n in (n1, n2, n3, n4))
    and (n1, n2, n3, n4) != (0, 0, 0, 0)
    and (n1, n2, n3, n4) != (255, 255, 255, 255)
)