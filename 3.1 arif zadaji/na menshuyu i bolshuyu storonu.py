# Вам требуется подобрать коробку, для вашего товара. Известно, что ширина, высота и глубина коробки – целые числа.
#
# Вашей программе даются на вход 3 числа с плавающей точкой – ширина, высота и глубина товара.
# Вам требуется подобрать для этого товара коробку. Выведите ширину, высоту и глубину коробки.
import math

a = float(input())
b = float(input())
c = float(input())
print(math.ceil(a))
print(math.ceil(b))
print(math.ceil(c)) #ceil на меньшую сторону
print(math.floor(a))
print(math.floor(b))
print(math.floor(c)) #floor на большую сторону