#
# Третий год:
# Остаток: (3 465 000 - 3 000 000) * (1 + 5 /100) = 488 250
#
# Вашей программе на вход идут переменные:
#
# a – стоимость квартиры,
# y – процент годовых,
# x – первоначальный взнос,
# b – ежегодная выплата.
